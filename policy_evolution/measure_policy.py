def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--model-type",   required=True, choices=["pretrain", "sft", "rl"])
    p.add_argument("--model-path",   required=True)
    p.add_argument("--config-path",  default=None, help="YAML config (pretrain only)")
    p.add_argument("--rollout-data", required=True, help="Path to 0.jsonl rollout file")
    p.add_argument("--parquet-dir",  required=True,
                   help="Directory containing eval parquets (e.g. eval_thinking/)")
    p.add_argument("--output-path",  required=True, help="Output .parquet path")
    p.add_argument("--shard-idx",    type=int, default=0,
                    help="Process only rows where row_idx %% num_shards == shard_idx (0-indexed)")
    p.add_argument("--num-shards",   type=int, default=1,
                    help="Total number of shards; 1 = no sharding (default)")
    p.add_argument("--batch-size",   type=int, default=256,
                   help="Micro-batch size for batched scoring (short contexts)")
    p.add_argument("--device",       default="cuda")
    return p.parse_args()


if __name__ == "__main__":
    process(parse_args())
