RANKS  = "12345678"
SQUARES = {f + r for f in FILES for r in RANKS}


def stored_text_to_ids(text: str, vocab: dict) -> list:
    """
    Convert stored JSONL text (space-separated, intra-move tokens concatenated)
    back to a list of token IDs.

    The decoder in LanTokenizer concatenates tokens within a single move without
    spaces, and separates moves with spaces.  For example:
      [N, g1, f3] is stored as "Ng1f3"  (not "N g1 f3")
      [P, d4, x, e5] is stored as "Pd4xe5"
      [<T>] is stored as "<T>"
    """
    ids = []
    for word in text.split():
        ids.extend(_word_to_ids(word, vocab))
    return ids


def _word_to_ids(word: str, vocab: dict) -> list:
    if word in vocab:
        return [vocab[word]]
    # Castling with check suffix: O-O+, O-O-O#, etc.
    if word.startswith("O-O"):
        base = "O-O-O" if word.startswith("O-O-O") else "O-O"
        ids = [vocab[base]]
        for ch in word[len(base):]:
            if ch in vocab:
                ids.append(vocab[ch])
        return ids
    # Regular LAN move — greedy parse: try 2-char (squares) then 1-char
    ids, i = [], 0
    while i < len(word):
        two = word[i : i + 2]
        if two in vocab:
            ids.append(vocab[two]); i += 2
        elif word[i] in vocab:
            ids.append(vocab[word[i]]); i += 1
        else:
            i += 1  # skip unknown character
    return ids


def ids_to_lan(token_ids: list, id2tok: dict) -> str:
    """Concatenate vocab strings for a move token ID sequence."""
    return "".join(id2tok.get(t, "?") for t in token_ids)


def _lan_word_to_uci(word: str, board: chess.Board) -> Optional[str]:
    """
    Convert a single concatenated LAN word (e.g. 'Ng1f3', 'Pd4xe5', 'O-O') to UCI.
    Returns None if the word doesn't parse as a move.
    """
    word_clean = word.rstrip("+#")
    if word_clean in {"O-O", "O-O-O"}:
        for mv in board.legal_moves:
            if board.is_castling(mv):
                dest_file = chess.square_file(mv.to_square)
                if word_clean == "O-O" and dest_file == 6:
                    return mv.uci()
                if word_clean == "O-O-O" and dest_file == 2:
                    return mv.uci()
        return None
    m = re.match(r"^[KQRBNP]([a-h][1-8])(?:x)?([a-h][1-8])(?:=([QRBN]))?[+#]?$", word)
    if not m:
        return None
    frm, to, promo = m.groups()
    return frm + to + (promo.lower() if promo else "")


def fen_from_lan_input(input_text: str) -> str:
    """
    Simulate all LAN moves in a JSONL input string to obtain the resulting FEN.
    The input is space-separated concatenated LAN words (e.g. 'Ng1f3 Pd7d5 ...<T>').
    Everything at and after <T> is ignored.
    Assumes games start from the standard initial position.
    """
    board = chess.Board()
    for word in input_text.split():
        if word.startswith("<"):   # special token (<T>, <bos>, etc.)
            break
        uci = _lan_word_to_uci(word, board)
        if uci:
            try:
                board.push(chess.Move.from_uci(uci))
            except Exception:
                break   # malformed — stop here
    return board.fen()


def legal_moves_with_tokens(board: chess.Board, vocab: dict) -> list:
    """
    Returns [(uci_str, token_id_list)] for all legal moves on the board.

    check/checkmate suffixes (+/#) are intentionally excluded: they are
    generated by the model AFTER the move tokens and are not part of the
    move's log-prob.
    """
    result = []
    for mv in board.legal_moves:
        uci = mv.uci()
        if board.is_castling(mv):
            base = "O-O" if chess.square_file(mv.to_square) == 6 else "O-O-O"
            toks = [vocab[base]]
        else:
            piece = board.piece_at(mv.from_square).symbol().upper()
            frm   = chess.square_name(mv.from_square)
            to    = chess.square_name(mv.to_square)
            toks  = [vocab[piece], vocab[frm]]
            if board.is_capture(mv):
                toks.append(vocab["x"])
            toks.append(vocab[to])
            if mv.promotion:
                toks += [vocab["="], vocab[chess.piece_symbol(mv.promotion).upper()]]
        result.append((uci, toks))
    return result


def uci_from_lan_token_ids(token_ids: list, id2tok: dict, board_before: chess.Board) -> Optional[str]:
    """Convert a LAN token ID sequence back to a UCI move string."""
    lan = ids_to_lan(token_ids, id2tok)
    for mv in board_before.legal_moves:
        if board_before.is_castling(mv):
            base = "O-O" if chess.square_file(mv.to_square) == 6 else "O-O-O"
            if lan.startswith(base):
                return mv.uci()
        else:
            piece = board_before.piece_at(mv.from_square).symbol().upper()
            frm   = chess.square_name(mv.from_square)
            to    = chess.square_name(mv.to_square)
            cap   = "x" if board_before.is_capture(mv) else ""
            promo = ("=" + chess.piece_symbol(mv.promotion).upper()) if mv.promotion else ""
            expected = f"{piece}{frm}{cap}{to}{promo}"
            if lan.startswith(expected):
                return mv.uci()
    return None


