def _kv_to_legacy(kv):
    """
    Normalize a past_key_values value to a legacy tuple-of-(K,V) layout we can
    slice/expand. transformers ≥4.42 returns a Cache object; older versions
    returned the legacy tuple directly. Cache exposes .to_legacy_cache() and
    is also iterable as (K,V) per layer, so this works either way.
    """
    if isinstance(kv, tuple):
        return kv
    return kv.to_legacy_cache()


def _kv_from_legacy(kv):
    """Wrap a legacy tuple-of-(K,V) in DynamicCache for newer transformers."""
    from transformers.cache_utils import DynamicCache
    return DynamicCache.from_legacy_cache(kv)


@torch.no_grad()
def score_moves_kvcache(
    model,
    ctx_ids: list,
    move_token_lists: list,
    device: str,
) -> tuple:
    """
    Score all legal moves against a shared context using batched KV cache.

    Returns:
      scores         : list[float]        — Σ log p per move
      per_tok_scores : list[list[float]]  — per-token log p per move

    Algorithm:
      1. One forward pass over the context → KV cache + last-position logits.
      2. Token 0 of every move: read directly from those logits (free).
      3. Token j (j ≥ 1): batch ALL moves that still have a j-th token into a
         single forward pass against the shared KV cache, expanded to batch N.
         Moves that are shorter than j+1 tokens drop out of the active set.

    This reduces sequential forward passes from N×(max_len-1) to (max_len-1),
    at the cost of O(N×ctx_len) KV cache memory (N≈30 moves, ctx_len≈330).

    KV cache is converted to legacy tuple form internally (so we can slice the
    batch dim cleanly) and re-wrapped in DynamicCache before each model call —
    transformers ≥4.50 / Qwen3 only accept Cache objects on the input side.
    """
    if not move_token_lists:
        return [], []

    N = len(move_token_lists)
    max_len = max(len(mv) for mv in move_token_lists)

    # ── Step 1: context forward pass ─────────────────────────────────────────
    ctx_t   = torch.tensor([ctx_ids], dtype=torch.long, device=device)
    ctx_out = model(ctx_t, use_cache=True)
    kv_ctx  = _kv_to_legacy(ctx_out.past_key_values)               # [(K,V)×layers], each [1,H,T,D]
    log_last = F.log_softmax(ctx_out.logits[0, -1, :], dim=-1)    # [vocab]

    # ── Step 2: token 0 — free from context logit ───────────────────────────
    per_tok_scores = [[None] * len(mv) for mv in move_token_lists]
    for i, mv in enumerate(move_token_lists):
        per_tok_scores[i][0] = log_last[mv[0]].item()

    if max_len == 1:
        scores = [per_tok_scores[i][0] for i in range(N)]
        return scores, per_tok_scores

    # ── Step 3+: batched forward passes, one per token position ──────────────
    # Expand KV cache from batch=1 to batch=N so all moves can share it.
    active_global = list(range(N))
    active_kv = tuple(
        (k.expand(N, -1, -1, -1).contiguous(), v.expand(N, -1, -1, -1).contiguous())
        for k, v in kv_ctx
    )

    for tok_pos in range(1, max_len):
        # Which moves in the current active set still need a token at tok_pos?
        still_local  = [j for j, i in enumerate(active_global)
                         if tok_pos < len(move_token_lists[i])]
        still_global = [active_global[j] for j in still_local]
        if not still_global:
            break

        # Input: previous token for each still-active move  [M, 1]
        inp = torch.tensor(
            [[move_token_lists[i][tok_pos - 1]] for i in still_global],
            dtype=torch.long, device=device,
        )

        # Select KV entries for only the still-active batch slots
        sel_kv = tuple(
            (k[still_local], v[still_local])
            for k, v in active_kv
        )

        out       = model(inp, past_key_values=_kv_from_legacy(sel_kv), use_cache=True)
        log_probs = F.log_softmax(out.logits[:, 0, :], dim=-1)    # [M, vocab]

        for batch_j, move_i in enumerate(still_global):
            target = move_token_lists[move_i][tok_pos]
            per_tok_scores[move_i][tok_pos] = log_probs[batch_j, target].item()

        active_global = still_global
        active_kv     = _kv_to_legacy(out.past_key_values)

    scores = [sum(per_tok_scores[i]) for i in range(N)]
    return scores, per_tok_scores


@torch.no_grad()
def batch_score_thinking(
    model,
    input_ids: list,
    thinking_id_lists: list,
    device: str,
    batch_size: int = 16,
) -> list:
    """
    Score K thinking blocks against the same context (input_ids) in batched
    forward passes.

    All K rows of one puzzle share input_ids (same game history), but each has
    a different thinking block.  Instead of K sequential single-sample forward
    passes we pack them into ceil(K/batch_size) padded batched passes.

    Full sequences are right-padded.  Because attention is causal, padding on
    the right does not affect log-probs at valid token positions.

    Returns: list of K lists, each containing per-token log probs for that
             row's thinking block.  Empty list for rows with no thinking tokens.
    """
    K = len(thinking_id_lists)
    results: list = [[] for _ in range(K)]

    valid = [(i, tids) for i, tids in enumerate(thinking_id_lists) if tids]
    if not valid:
        return results

    ctx_len = len(input_ids)

    for sub_start in range(0, len(valid), batch_size):
        sub      = valid[sub_start : sub_start + batch_size]
        B        = len(sub)
        seqs     = [input_ids + tids for _, tids in sub]
        max_len  = max(len(s) for s in seqs)

        # Right-padded input (right-shifted for LM: feed seq[:-1], label seq[1:])
        inp  = torch.zeros(B, max_len - 1, dtype=torch.long, device=device)
        mask = torch.zeros(B, max_len - 1, dtype=torch.long, device=device)
        for b, seq in enumerate(seqs):
            n = len(seq) - 1
            inp[b, :n]  = torch.tensor(seq[:-1])
            mask[b, :n] = 1

        logits = model(input_ids=inp, attention_mask=mask).logits  # [B, max_len-1, vocab]
        lps    = F.log_softmax(logits, dim=-1)

        for b, (orig_i, tids) in enumerate(sub):
            results[orig_i] = [
                lps[b, ctx_len - 1 + j, tid].item()
                for j, tid in enumerate(tids)
            ]

    return results


