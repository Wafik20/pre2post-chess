#!/usr/bin/env python3
"""
measure_policy.py — Teacher-forcing policy measurement for chess models.

For each row in a rollout JSONL (already generated), re-scores:
  • All legal moves at each board position (unnormalized log-probs + per-token breakdown)
  • The thinking block token-by-token (SFT/RL only)

Output: one parquet row per (jsonl_row, turn) with the full probability matrix.

Usage:
  python measure_policy.py \
    --model-type sft \
    --model-path /path/to/hf_checkpoint \
    --rollout-data /path/to/0.jsonl \
    --parquet-dir  /path/to/eval_parquets \
    --output-path  /path/to/raw_scores.parquet \
    --batch-size   256
"""

