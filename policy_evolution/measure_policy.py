def load_model_and_vocab(model_type: str, model_path: str, config_path: Optional[str], device: str):
    """
    Returns (model, vocab, bos_id, id2tok).

    All three model types (pretrain, sft, rl) are stored as standard HuggingFace
    checkpoints with a vocab.json alongside the weights.  Pretrain models have a
    smaller vocab (81 tokens, no <T>/<call_env>) but are otherwise loaded
    identically to SFT/RL models.
    """
    from transformers import AutoModelForCausalLM

    vocab_json = Path(model_path) / "vocab.json"
    with open(vocab_json) as f:
        vocab = json.load(f)
    bos_id = vocab["<bos>"]

    model = AutoModelForCausalLM.from_pretrained(
        model_path, trust_remote_code=True, torch_dtype=torch.bfloat16
    ).to(device)
    model.eval()

    id2tok = {v: k for k, v in vocab.items()}
    return model, vocab, bos_id, id2tok


