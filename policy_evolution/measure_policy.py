def parse_row(row: dict, vocab: dict, bos_id: int, model_type: str) -> dict:
    """
    Parse a JSONL rollout row into structured fields.

    Returns dict with keys:
      input_ids       : list[int] — prompt token IDs (with BOS prepended)
      thinking_ids    : list[int] — thinking block token IDs (SFT/RL only)
      t_end_id        : int       — </T> token ID
      call_env_id     : int       — <call_env> token ID
      model_turns     : list of {token_ids, lan_str}  — model's generated moves
      env_turns       : list of {token_ids}            — env's moves
    """
    input_ids    = [bos_id] + stored_text_to_ids(row["input"], vocab)
    t_end_id     = vocab.get("</T>", -1)
    call_env_id  = vocab.get("<call_env>", -1)

    output = row.get("output", "")
    thinking_ids = []

    if model_type != "pretrain" and "</T>" in output:
        thinking_text   = output[: output.index("</T>")]
        move_seq_text   = output[output.index("</T>") + len("</T>") :].strip()
        thinking_ids    = stored_text_to_ids(thinking_text, vocab)
    else:
        move_seq_text = output

    # Split on <call_env> → alternating model/env segments
    segments   = move_seq_text.split("<call_env>")
    model_turns, env_turns = [], []
    for i, seg in enumerate(segments[:-1]):
        toks = stored_text_to_ids(seg.strip(), vocab)
        if i % 2 == 0:
            model_turns.append({"token_ids": toks})
        else:
            env_turns.append({"token_ids": toks})

    return {
        "input_ids":    input_ids,
        "thinking_ids": thinking_ids,
        "t_end_id":     t_end_id,
        "call_env_id":  call_env_id,
        "model_turns":  model_turns,
        "env_turns":    env_turns,
    }


# ─────────────────────────────────────────────────────────────────────────────
# Parquet lookup (for FEN, env_replies, puzzle metadata)
# ─────────────────────────────────────────────────────────────────────────────

def build_parquet_lookup(parquet_dir: str, data_sources: set) -> dict:
    """
    Load all relevant parquet files and build a lookup:
      {(data_source, fen): extra_info_dict}

    Key is (data_source, FEN) — the board state at the start of the model's
    first move.  This is the only reliable unique key shared between the
    parquet (extra_info['FEN']) and the JSONL (reconstructed from input tokens).
    """
    lookup = {}
    parquet_dir = Path(parquet_dir)
    for ds in data_sources:
        candidates = [
            parquet_dir / f"{ds}_multi_turn.parquet",
            parquet_dir / f"{ds}.parquet",
        ]
        found = next((p for p in candidates if p.exists()), None)
        if found is None:
            print(f"  WARNING: no parquet found for data_source={ds!r} in {parquet_dir}")
            continue
        df = pd.read_parquet(found)
        for _, row in df.iterrows():
            ei  = row["extra_info"]
            fen = ei["FEN"] if isinstance(ei, dict) else dict(ei)["FEN"]
            key = (row["data_source"], fen)
            lookup[key] = ei
    return lookup


# ─────────────────────────────────────────────────────────────────────────────
# Main processing loop
# ─────────────────────────────────────────────────────────────────────────────

def _score_one_row(
    row_idx: int,
    row: dict,
    parsed: dict,
    trace_per_tok: list,
    ei: dict,
    puzzle_id: str,
    model,
    vocab: dict,
    id2tok: dict,
    model_type: str,
    model_path: str,
    device: str,
) -> tuple:
    """
    Score all legal moves for every turn of one rollout row.
    Returns (records_list, ok: bool).
    """
    fen_start   = ei.get("FEN", "")
    env_replies = list(ei.get("env_replies", []))
    rating      = ei.get("Rating", None)
    gt_moves    = ast.literal_eval(row["ground_truth"])

    input_ids    = parsed["input_ids"]
    thinking_ids = parsed["thinking_ids"]
    t_end_id     = parsed["t_end_id"]
    call_env_id  = parsed["call_env_id"]
    model_turns  = parsed["model_turns"]

    try:
        board = chess.Board(fen_start)
    except Exception:
        return [], False

    cond_ctx = list(input_ids)
    if model_type != "pretrain":
        cond_ctx = cond_ctx + thinking_ids + ([t_end_id] if t_end_id >= 0 else [])

    records = []
    for turn_idx, gt_uci in enumerate(gt_moves):
        legal      = legal_moves_with_tokens(board, vocab)
        uci_list   = [u for u, _ in legal]
        move_toks  = [t for _, t in legal]
        move_lans  = [ids_to_lan(t, id2tok) for t in move_toks]

        gen_toks   = model_turns[turn_idx]["token_ids"] if turn_idx < len(model_turns) else []
        parsed_uci = uci_from_lan_token_ids(gen_toks, id2tok, board)

        scores, per_tok_scores = score_moves_kvcache(model, cond_ctx, move_toks, device)

        records.append({
            "row_idx":                row_idx,
            "puzzle_id":              puzzle_id,
            "data_source":            row["data_source"],
            "prompt":                 row.get("input", ""),
            "model_type":             model_type,
            "model_path":             model_path,
            "turn":                   turn_idx,
            "outcome":                float(row.get("outcome_score", row.get("score", 0))),
            "rating":                 rating,
            "fen":                    board.fen(),
            "gt_uci":                 gt_uci,
            "parsed_move_uci":        parsed_uci,
            "legal_moves_uci":        uci_list,
            "legal_moves_lan":        move_lans,
            "legal_moves_token_ids":  move_toks,
            "log_pi_tilde":           scores,
            "log_pi_tilde_per_token": per_tok_scores,
            "context_token_ids":      cond_ctx,
            "thinking_token_ids":     thinking_ids if model_type != "pretrain" else None,
            "log_pi_trace_per_token": trace_per_tok if model_type != "pretrain" else None,
            "log_pi_trace":           sum(trace_per_tok) if trace_per_tok else None,
            "thinking_len":           len(thinking_ids),
        })

        try:
            board.push(chess.Move.from_uci(gt_uci))
        except Exception:
            break

        if turn_idx < len(gt_moves) - 1:
            gt_move_toks = next((t for u, t in legal if u == gt_uci), gen_toks)
            cond_ctx = cond_ctx + gt_move_toks + ([call_env_id] if call_env_id >= 0 else [])

            if turn_idx < len(env_replies):
                env_lan  = env_replies[turn_idx]
                env_toks = stored_text_to_ids(env_lan, vocab)
                cond_ctx = cond_ctx + env_toks

                env_uci = None
                for mv in board.legal_moves:
                    if board.is_castling(mv):
                        base = "O-O" if chess.square_file(mv.to_square) == 6 else "O-O-O"
                        if env_lan.rstrip("+#").startswith(base):
                            env_uci = mv.uci(); break
                    else:
                        piece = board.piece_at(mv.from_square).symbol().upper()
                        frm   = chess.square_name(mv.from_square)
                        to    = chess.square_name(mv.to_square)
                        cap   = "x" if board.is_capture(mv) else ""
                        promo = ("=" + chess.piece_symbol(mv.promotion).upper()) if mv.promotion else ""
                        if env_lan.rstrip("+#").startswith(f"{piece}{frm}{cap}{to}{promo}"):
                            env_uci = mv.uci(); break
                if env_uci:
                    try:
                        board.push(chess.Move.from_uci(env_uci))
                    except Exception:
                        break

    return records, True


def process(args):
    device = args.device if torch.cuda.is_available() else "cpu"
    print(f"Device: {device}")

    # ── Load rollout JSONL ──────────────────────────────────────────────────
    print(f"Loading rollout data: {args.rollout_data}")
    with open(args.rollout_data) as f:
        rows = [json.loads(line) for line in f]
    print(f"  {len(rows)} rows loaded")
    if args.num_shards > 1:
        if not (0 <= args.shard_idx < args.num_shards):
            raise ValueError(f"shard_idx={args.shard_idx} out of range for num_shards={args.num_shards}")
        rows = [r for i, r in enumerate(rows) if i % args.num_shards == args.shard_idx]
        print(f"  shard {args.shard_idx}/{args.num_shards}: kept {len(rows)} rows")

    # ── Build parquet lookup ────────────────────────────────────────────────
    data_sources = {r["data_source"] for r in rows}
    print(f"Data sources: {data_sources}")
    lookup = build_parquet_lookup(args.parquet_dir, data_sources)
    print(f"  {len(lookup)} puzzles in parquet lookup")

    # ── Load model + vocab ──────────────────────────────────────────────────
    print(f"Loading {args.model_type} model from {args.model_path}")
    model, vocab, bos_id, id2tok = load_model_and_vocab(
        args.model_type, args.model_path, args.config_path, device
    )
    print(f"  Vocab size: {len(vocab)}, BOS={bos_id}")

    # ── Group rows by puzzle (same FEN → same input_ids → can share thinking
    #    batch scoring) ────────────────────────────────────────────────────────
    from collections import defaultdict
    puzzle_groups: dict = defaultdict(list)
    for row_idx, row in enumerate(rows):
        fen = fen_from_lan_input(row["input"])
        key = (row["data_source"], fen)
        puzzle_groups[key].append((row_idx, row))

    records = []
    skipped = 0

    for key, puzzle_row_list in tqdm(puzzle_groups.items(), desc="Scoring puzzles"):
        extra_info = lookup.get(key)
        if extra_info is None:
            skipped += len(puzzle_row_list)
            continue

        ei = extra_info if isinstance(extra_info, dict) else dict(extra_info)
        puzzle_id = ei.get("PuzzleId", f"puzzle_{key[0]}_{key[1][:8]}")

        # input_ids is identical for all rows of a puzzle (same game history)
        _, first_row = puzzle_row_list[0]
        input_ids = [bos_id] + stored_text_to_ids(first_row["input"], vocab)

        # Parse all rows of this puzzle
        parsed_list = [
            (row_idx, row, parse_row(row, vocab, bos_id, args.model_type))
            for row_idx, row in puzzle_row_list
        ]

        # ── Batch-score all thinking blocks for this puzzle in one GPU pass ──
        # All K rows share input_ids; their thinking blocks differ.
        # batch_score_thinking packs them into ceil(K/batch_size) padded passes
        # instead of K sequential single-sample forward passes.
        if args.model_type != "pretrain":
            thinking_id_lists = [p[2]["thinking_ids"] for p in parsed_list]
            trace_per_tok_list = batch_score_thinking(
                model, input_ids, thinking_id_lists, device, args.batch_size
            )
        else:
            trace_per_tok_list = [[] for _ in parsed_list]

        # ── Per-row move scoring ─────────────────────────────────────────────
        for (row_idx, row, parsed), trace_per_tok in zip(parsed_list, trace_per_tok_list):
            row_records, ok = _score_one_row(
                row_idx, row, parsed, trace_per_tok, ei, puzzle_id,
                model, vocab, id2tok, args.model_type, args.model_path, device,
            )
            if ok:
                records.extend(row_records)
            else:
                skipped += 1

    print(f"\nDone. {len(records)} records written, {skipped} rows skipped.")

    out_path = Path(args.output_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(records).to_parquet(out_path, index=False)
    print(f"Saved to {out_path}")


